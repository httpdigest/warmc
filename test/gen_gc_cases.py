"""Mechanical garbage-collection cases: the ones that are a size rather than a
shape, and so are better counted than typed.

Written into build/ rather than beside test/cases_gc/gc.wat, so there is no
checked-in file that looks hand-written and is silently overwritten -- the same
rule test/gen_pressure.py and test/gen_binary_cases.py already follow.

What is here is the *reach* of a field offset.  A field access is
`ldr Xd, [Xobj, #off]`, whose immediate is scaled by the access width, so the
fallback to an offset in a register is taken when `off >> log2(width)` passes
4,095 -- at byte offset 32,760 for an i64, 16,380 for an i32, 8,190 for an i16
and 4,095 for an i8.  A limit expressed in bytes rather than in units of the
access width is exactly the mistake the instance layout already made once, and
the narrow case is the one that gets forgotten: an i8 field runs out eight
times sooner than an i64 one.

So `$mixed` puts a run of v128 fields in front -- the cheapest way to push a
byte offset up, sixteen bytes at a time -- and then one field of each width on
each side of *its own* boundary.  The alternative, a struct of sixteen thousand
i32 fields, is past the ten thousand the spec's implementation limits allow and
`wasm-tools` refuses it.

And the *reach of a type index*.  The allocation fast path composes a header
by adding `type_index << GC_TYPE_SHIFT` to a base the runtime publishes, and
an add's immediate is twelve bits -- so past index 511 the index has to be
materialised in a register instead.  That threshold moved when the mark colour
took a second bit, which is exactly the kind of number that is only ever right
by accident: `$manytypes` puts six hundred struct types in a module and
allocates from the last one, so the wide form is emitted and its object is
read back after a collection.

And the *reach of the literal pool*.  A float constant normally loads from a
pool behind the function, but where the function could outgrow the 1 MB reach
of a literal load -- a few thousand instructions, at the estimate's 128 bytes
apiece -- the constant is built through x16 instead (rax on x64).  array.set
held the element's address in that same register while it read the value, so a
constant rebuilt at the store sent the store wherever the constant's bits
pointed: Kotlin's doubleArrayOf in a long main.  The `farpool_*` functions open
with eight thousand memory.fills to put their pools out of reach -- fills of
the same three locals, which make no value the naive allocator would give a
slot of its own -- and keep a dozen doubles live across a call in the loop,
more than the callee-saved registers hold, so -inf is rebuilt at its store
instead of keeping a register.  One stores into an array element, the other
into a struct field past the reach of a scaled offset, whose address goes into
x16 too.  Each function holds a single store: two would earn the constant a
register of its own.
"""
import os
import sys

NV = 4100

LIMITS = {"i64": 8 * 4096, "i32": 4 * 4096, "i16": 2 * 4096, "i8": 1 * 4096}

def probes(n):
    """Indices around the v128 boundary, and the two ends."""
    out = [0, 1, 4093, 4094, 4095, 4096, n - 1]
    return sorted({k for k in out if 0 <= k < n})

def gen():
    L = []
    A = L.append
    A(";; Generated by test/gen_gc_cases.py -- do not edit.")
    A("(module")

    A("  (type $wv (struct")
    A("    " + " ".join("(field (mut v128))" for _ in range(NV)) + "))")

    narrow = []
    fields = []
    def emit_pad(nbytes):
        """Pad with v128 fields until the payload reaches nbytes."""
        have = 16 + 16 * len(fields)
        while have < nbytes:
            fields.append("v128")
            have += 16
        return have

    layout = []
    for ty, lim in (("i64", LIMITS["i64"]), ("i32", LIMITS["i32"]),
                    ("i16", LIMITS["i16"]), ("i8", LIMITS["i8"])):

        emit_pad(lim - 16 * 8)
        near = len(fields)
        fields.append(ty)

        emit_pad(lim + 16 * 8)
        far = len(fields)
        fields.append(ty)
        layout.append((ty, near, far))

    A("  (type $mixedwide (struct")
    A("    " + " ".join("(field (mut %s))" % t for t in fields) + "))")

    A("  (func $fail (unreachable))")
    A("  (func $eq32 (param i32 i32)")
    A("    (if (i32.ne (local.get 0) (local.get 1)) (then (call $fail))))")
    A("  (func $eq64 (param i64 i64)")
    A("    (if (i64.ne (local.get 0) (local.get 1)) (then (call $fail))))")

    A('  (func (export "wide_v128")')
    A("    (local $o (ref $wv))")
    A("    (local.set $o (struct.new_default $wv))")
    for k in probes(NV):
        A("    (struct.set $wv %d (local.get $o) (v128.const i64x2 %d %d))"
          % (k, k + 1, ~k & 0xFFFF))
    for k in probes(NV):
        A("    (call $eq64 (i64x2.extract_lane 0 (struct.get $wv %d (local.get $o)))"
          " (i64.const %d))" % (k, k + 1))
        A("    (call $eq64 (i64x2.extract_lane 1 (struct.get $wv %d (local.get $o)))"
          " (i64.const %d))" % (k, ~k & 0xFFFF))
    A("  )")

    A('  (func (export "wide_narrow")')
    A("    (local $o (ref $mixedwide))")
    A("    (local.set $o (struct.new_default $mixedwide))")
    val = {}
    n = 0
    for ty, near, far in layout:
        for k in (near, far):
            n += 1
            v = {"i64": 0x0123456789ab0000 + n, "i32": 0x12340000 + n,
                 "i16": 0x1000 + n, "i8": 0x40 + n}[ty]
            val[k] = (ty, v)
            A("    (struct.set $mixedwide %d (local.get $o) (%s.const %d))"
              % (k, "i64" if ty == "i64" else "i32", v))
    for k in sorted(val):
        ty, v = val[k]
        if ty == "i64":
            A("    (call $eq64 (struct.get $mixedwide %d (local.get $o)) (i64.const %d))"
              % (k, v))
        elif ty == "i32":
            A("    (call $eq32 (struct.get $mixedwide %d (local.get $o)) (i32.const %d))"
              % (k, v))
        else:
            A("    (call $eq32 (struct.get_u $mixedwide %d (local.get $o)) (i32.const %d))"
              % (k, v))
    A("  )")

    A('  (func (export "wide_distinct")')
    A("    (local $a (ref $wv)) (local $b (ref $wv))")
    A("    (local.set $a (struct.new_default $wv))")
    A("    (local.set $b (struct.new_default $wv))")
    for i, who in (("0", "$a"), ("1", "$b")):
        A("    (struct.set $wv 0 (local.get %s) (v128.const i64x2 %s 0))" % (who, i))
        A("    (struct.set $wv %d (local.get %s) (v128.const i64x2 %s 0))"
          % (NV - 1, who, i))
    for i, who in (("0", "$a"), ("1", "$b")):
        A("    (call $eq64 (i64x2.extract_lane 0 (struct.get $wv 0 (local.get %s)))"
          " (i64.const %s))" % (who, i))
        A("    (call $eq64 (i64x2.extract_lane 0 (struct.get $wv %d (local.get %s)))"
          " (i64.const %s))" % (NV - 1, who, i))
    A("  )")

    NT = 600
    for i in range(NT - 1):
        A("  (type $t%d (struct (field $v%d (mut i32))))" % (i, i))

    A("  (type $t%d (struct (field $v%d (mut i64)) (field i64) (field i64)"
      " (field i64) (field i64) (field i64) (field i64) (field i64)))"
      % (NT - 1, NT - 1))
    A("  (global $sink (mut anyref) (ref.null any))")
    A('  (func (export "manytypes") (param $n i32)')
    A("    (local $o (ref $t%d)) (local $i i32)" % (NT - 1))
    A("    (local.set $o (struct.new $t%d (i64.const 4242) (i64.const 0)"
      " (i64.const 0) (i64.const 0) (i64.const 0) (i64.const 0) (i64.const 0)"
      " (i64.const 0)))" % (NT - 1))

    A("    (global.set $sink (local.get $o))")
    A("    (block $done")
    A("      (br_if $done (i32.eqz (local.get $n)))")
    A("      (loop $l")
    A("        (global.set $sink (struct.new $t0 (i32.const 1)))")
    A("        (global.set $sink (struct.new $t%d (i64.const 2) (i64.const 0)"
      " (i64.const 0) (i64.const 0) (i64.const 0) (i64.const 0) (i64.const 0)"
      " (i64.const 0)))" % (NT - 1))
    A("        (local.set $i (i32.add (local.get $i) (i32.const 1)))")
    A("        (br_if $l (i32.lt_u (local.get $i) (local.get $n)))))")
    A("    (call $eq64 (struct.get $t%d $v%d (local.get $o)) (i64.const 4242))"
      % (NT - 1, NT - 1))
    A("  )")

    NP = 12
    FARF = LIMITS["i64"] // 16
    A("  (type $adbl (array (mut f64)))")
    A("  (type $farf (struct")
    A("    " + " ".join("(field v128)" for _ in range(FARF)) + " (field (mut f64))))")
    A("  (type $v (func))")
    A("  (memory 1)")
    A("  (table 2 funcref)")
    A("  (elem (i32.const 0) $tick $tock)")
    A("  (global $gk (mut i32) (i32.const 0))")
    A("  (global $gi (mut i32) (i32.const 1))")
    A("  (global $gs (mut f64) (f64.const 0))")
    A("  (global $gdbl (mut (ref null $adbl)) (ref.null $adbl))")
    A("  (global $gfar (mut (ref null $farf)) (ref.null $farf))")
    A("  (func $tick (global.set $gk (i32.add (global.get $gk) (i32.const 1))))")
    A("  (func $tock (global.set $gk (i32.add (global.get $gk) (i32.const 2))))")

    def farpool(name, make, store, load):
        A('  (func (export "%s")' % name)
        A("    (local $i i32) (local $p i32) "
          + " ".join("(local $p%d f64)" % k for k in range(NP)))
        A("    (local.set $p (global.get $gk))")
        A("    (local.set $i (global.get $gi))")
        for _ in range(8000):
            A("    (memory.fill (local.get $p) (local.get $i) (local.get $i))")
        A("    (local.set $i (i32.const 0))")
        A("    " + make)
        for k in range(NP):
            A("    (local.set $p%d (f64.convert_i32_s (global.get $gi)))" % k)
        A("    (loop $l")
        A("      (call_indirect (type $v) (global.get $gi))")
        for k in range(NP):
            A("      (local.set $p%d (f64.add (local.get $p%d) (f64.const %d.5)))"
              % (k, k, k))
        A("      " + store)
        A("      (local.set $i (i32.add (local.get $i) (i32.const 1)))")
        A("      (br_if $l (i32.lt_u (local.get $i) (i32.const 8))))")
        total = "(f64.const 0)"
        for k in range(NP):
            total = "(f64.add %s (local.get $p%d))" % (total, k)
        A("    (global.set $gs %s)" % total)
        A("    (call $eq64 (i64.reinterpret_f64 %s) (i64.const 0xfff0000000000000))"
          % load)
        A("  )")

    farpool("farpool_array",
            "(global.set $gdbl (array.new $adbl (f64.const 0) (i32.const 8)))",
            "(array.set $adbl (global.get $gdbl) (local.get $i) (f64.const -inf))",
            "(array.get $adbl (global.get $gdbl) (i32.const 3))")
    farpool("farpool_field",
            "(global.set $gfar (struct.new_default $farf))",
            "(struct.set $farf %d (global.get $gfar) (f64.const -inf))" % FARF,
            "(struct.get $farf %d (global.get $gfar))" % FARF)
    A(")")
    return "\n".join(L) + "\n"

def main():
    out = sys.argv[1] if len(sys.argv) > 1 else "build"
    os.makedirs(out, exist_ok=True)
    path = os.path.join(out, "gcgen.wat")
    tmp = "%s.%d.tmp" % (path, os.getpid())
    with open(tmp, "w") as f:
        f.write(gen())
    os.replace(tmp, path)
    print(path)

main()
