"""Generate the three addressing benchmark modules.

The same six kernels, over the same data, at the same byte offsets, compiled
three ways:

  addr32.wat     one plain 32-bit memory -- what the back end was built for
  addrmulti.wat  three 32-bit memories, the arrays spread across them
  addr64.wat     one memory with a 64-bit index space

They exist as a set rather than one at a time because the interesting number
is not what any of them costs but what the *second and third* cost over the
first.  A single 32-bit memory is the shape `pass_mem_ptr`,
`pass_addr_offsets` and `pass_vectorize` were written for and the only one
they used to run on, and a 64-bit index is bounds-checked at every
optimisation level because the guard reservation cannot cover it -- so the gap
between these three modules is the price of the two features, measured rather
than estimated.

They are generated rather than written out three times because that gap is
only meaningful while the kernels are identical, and three hand-maintained
copies of the same loop do not stay identical.  Every export also returns the
same checksum in all three, which is a differential test the suite gets for
free: addr64 disagreeing with addr32 is a 64-bit addressing bug that no
comparison against the interpreter has to be arranged to catch.

The data is written by a start function rather than a data segment: an 8 KiB
segment is 32 KiB of escapes in the source, and the arrays have to hold the
same bytes in all three modules whatever memory they live in.
"""
import os
import sys

OUT = sys.argv[1] if len(sys.argv) > 1 else "test/bench"

NA = 1024
HN = 256

OFF = {"A": 0, "B": 4096, "C": 8192, "H": 12288, "S": 16384, "D": 20480}

LAYOUT = {
    "addr32":    {"A": 0, "B": 0, "C": 0, "H": 0, "S": 0, "D": 0},
    "addrmulti": {"A": 0, "B": 1, "C": 2, "H": 0, "S": 1, "D": 2},
    "addr64":    {"A": 0, "B": 0, "C": 0, "H": 0, "S": 0, "D": 0},
}

class Emit:
    """The parts of an access the three variants disagree about."""

    def __init__(self, variant):
        self.variant = variant
        self.wide = variant == "addr64"
        self.it = "i64" if self.wide else "i32"
        self.layout = LAYOUT[variant]

    def at(self, arr, addr):
        """`memory offset=... (address)`, the tail of every access below."""
        mem = "" if self.variant != "addrmulti" else "$m%d " % self.layout[arr]
        return "%soffset=%d %s" % (mem, OFF[arr], addr)

    def wide_(self, expr):
        """An i32 expression used where an address is wanted."""
        return "(i64.extend_i32_u %s)" % expr if self.wide else expr

    def narrow(self, local):
        """An index local used where an i32 value is wanted."""
        return "(i32.wrap_i64 (local.get %s))" % local if self.wide \
            else "(local.get %s)" % local

    def k(self, v):
        return "(%s.const %d)" % (self.it, v)

    def scaled(self, local, log2):
        return "(%s.shl (local.get %s) %s)" % (self.it, local, self.k(log2))

    def bump(self, local):
        return "(local.set %s (%s.add (local.get %s) %s))" % (
            local, self.it, local, self.k(1))

    def below(self, local, limit):
        return "(%s.lt_u (local.get %s) %s)" % (self.it, local, limit)

    def memories(self):
        if self.variant == "addrmulti":
            return "  (memory $m0 1)\n  (memory $m1 1)\n  (memory $m2 1)\n"
        if self.wide:
            return "  (memory $m i64 1)\n"
        return "  (memory $m 1)\n"

def loop(label, body, cond, indent=6):
    """A counted loop written the way a producer writes one: the test is at
    the bottom, so an entered loop runs its body at least once."""
    pad = " " * indent
    inner = "\n".join(pad + "  " + l for l in body)
    return "%s(loop %s\n%s\n%s  (br_if %s %s))" % (pad, label, inner, pad, label, cond)

def clamp(name, limit):
    """Hold a caller's count inside the arrays.

    Every kernel takes its trip count as a parameter rather than a constant,
    so nothing here can be unrolled or folded against a known bound -- which
    is also why the count has to be clamped rather than trusted."""
    return ("    (if (i32.gt_u (local.get %s) (i32.const %d))\n"
            "      (then (local.set %s (i32.const %d))))" % (name, limit, name, limit))

def gen(variant):
    e = Emit(variant)
    n_elems = e.wide_("(local.get $n)")
    out = []
    w = out.append

    w(";; Addressing benchmarks: the %s variant."
      "  GENERATED by test/gen_bench.py.\n"
      ";;\n"
      ";; Six kernels over three i32 arrays and two byte arrays, each taking its\n"
      ";; element count as a parameter so the trip count is opaque to the\n"
      ";; compiler.  The three variants differ only in where the arrays live and\n"
      ";; how wide an index is; every export returns the same checksum in all\n"
      ";; three, so comparing them is a test as well as a measurement.\n"
      "(module\n" % variant)
    w(e.memories())

    draw = ["(local.set $s (i32.xor (local.get $s) (i32.shl (local.get $s) (i32.const 13))))",
            "(local.set $s (i32.xor (local.get $s) (i32.shr_u (local.get $s) (i32.const 17))))",
            "(local.set $s (i32.xor (local.get $s) (i32.shl (local.get $s) (i32.const 5))))"]
    body = []
    for arr in ("A", "B", "S"):
        body += draw
        body.append("(i32.store %s (local.get $s))" % e.at(arr, e.scaled("$i", 2)))
    body.append(e.bump("$i"))
    w("\n"
      "  ;; A, B and S get the same pseudorandom bytes in every variant, so the\n"
      "  ;; checksums below can be compared across the three.\n"
      "  (func $init (local $i %s) (local $s i32)\n"
      "    (local.set $s (i32.const 0x2545F491))\n"
      "%s)\n"
      "  (start $init)\n"
      % (e.it, loop("$l", body[:-1] + [body[-1]], e.below("$i", e.k(NA)), 4)))

    w("\n"
      "  ;; acc += A[i]\n"
      "  (func (export \"k_sum\") (param $n i32) (result i32)\n"
      "    (local $i %s) (local $acc i32)\n"
      "%s\n"
      "    (block $done\n"
      "      (br_if $done (i32.eqz (local.get $n)))\n"
      "%s)\n"
      "    (local.get $acc))\n"
      % (e.it, clamp("$n", NA),
         loop("$l",
              ["(local.set $acc (i32.add (local.get $acc) (i32.load %s)))"
               % e.at("A", e.scaled("$i", 2)),
               e.bump("$i")],
              e.below("$i", n_elems))))

    w("\n"
      "  ;; C[i] = A[i]*3 + B[i], then acc += C[i] in a second pass\n"
      "  (func (export \"k_axpy\") (param $n i32) (result i32)\n"
      "    (local $i %s) (local $acc i32)\n"
      "%s\n"
      "    (block $done\n"
      "      (br_if $done (i32.eqz (local.get $n)))\n"
      "%s\n"
      "      (local.set $i %s)\n"
      "%s)\n"
      "    (local.get $acc))\n"
      % (e.it, clamp("$n", NA),
         loop("$l",
              ["(i32.store %s" % e.at("C", e.scaled("$i", 2)),
               "  (i32.add (i32.mul (i32.load %s) (i32.const 3))"
               % e.at("A", e.scaled("$i", 2)),
               "           (i32.load %s)))" % e.at("B", e.scaled("$i", 2)),
               e.bump("$i")],
              e.below("$i", n_elems)),
         e.k(0),
         loop("$l2",
              ["(local.set $acc (i32.add (local.get $acc) (i32.load %s)))"
               % e.at("C", e.scaled("$i", 2)),
               e.bump("$i")],
              e.below("$i", n_elems))))

    gather = e.wide_("(i32.shl (i32.and (i32.load %s) (i32.const %d)) (i32.const 2))"
                     % (e.at("B", e.scaled("$i", 2)), NA - 1))
    w("\n"
      "  ;; acc += A[B[i] & %d] -- a data-dependent address\n"
      "  (func (export \"k_gather\") (param $n i32) (result i32)\n"
      "    (local $i %s) (local $acc i32)\n"
      "%s\n"
      "    (block $done\n"
      "      (br_if $done (i32.eqz (local.get $n)))\n"
      "%s)\n"
      "    (local.get $acc))\n"
      % (NA - 1, e.it, clamp("$n", NA),
         loop("$l",
              ["(local.set $acc (i32.add (local.get $acc) (i32.load %s)))"
               % e.at("A", gather),
               e.bump("$i")],
              e.below("$i", n_elems))))

    bucket = e.wide_("(i32.shl (i32.and (i32.load %s) (i32.const %d)) (i32.const 2))"
                     % (e.at("A", e.scaled("$i", 2)), HN - 1))
    w("\n"
      "  ;; a %d-bucket histogram of A's low byte, folded into one number\n"
      "  (func (export \"k_hist\") (param $n i32) (result i32)\n"
      "    (local $i %s) (local $acc i32) (local $p %s)\n"
      "%s\n"
      "%s\n"
      "    (local.set $i %s)\n"
      "    (block $done\n"
      "      (br_if $done (i32.eqz (local.get $n)))\n"
      "%s)\n"
      "    (local.set $i %s)\n"
      "%s\n"
      "    (local.get $acc))\n"
      % (HN, e.it, e.it, clamp("$n", NA),
         loop("$z",
              ["(i32.store %s (i32.const 0))" % e.at("H", e.scaled("$i", 2)),
               e.bump("$i")],
              e.below("$i", e.k(HN)), 4),
         e.k(0),
         loop("$l",
              ["(local.set $p %s)" % bucket,
               "(i32.store %s (i32.add (i32.load %s) (i32.const 1)))"
               % (e.at("H", "(local.get $p)"), e.at("H", "(local.get $p)")),
               e.bump("$i")],
              e.below("$i", n_elems)),
         e.k(0),
         loop("$f",
              ["(local.set $acc (i32.add (local.get $acc)",
               "  (i32.mul (i32.load %s)" % e.at("H", e.scaled("$i", 2)),
               "           (i32.add %s (i32.const 1)))))" % e.narrow("$i"),
               e.bump("$i")],
              e.below("$i", e.k(HN)), 4)))

    w("\n"
      "  ;; D[i] = S[i] ^ 0x5a over 4n bytes, then acc += D[i]\n"
      "  (func (export \"k_bytes\") (param $n i32) (result i32)\n"
      "    (local $i %s) (local $acc i32) (local $nb %s)\n"
      "%s\n"
      "    (local.set $nb %s)\n"
      "    (block $done\n"
      "      (br_if $done (i32.eqz (local.get $n)))\n"
      "%s\n"
      "      (local.set $i %s)\n"
      "%s)\n"
      "    (local.get $acc))\n"
      % (e.it, e.it, clamp("$n", NA),
         e.wide_("(i32.shl (local.get $n) (i32.const 2))"),
         loop("$l",
              ["(i32.store8 %s" % e.at("D", "(local.get $i)"),
               "  (i32.xor (i32.load8_u %s) (i32.const 0x5a)))"
               % e.at("S", "(local.get $i)"),
               e.bump("$i")],
              e.below("$i", "(local.get $nb)")),
         e.k(0),
         loop("$l2",
              ["(local.set $acc (i32.add (local.get $acc) (i32.load8_u %s)))"
               % e.at("D", "(local.get $i)"),
               e.bump("$i")],
              e.below("$i", "(local.get $nb)"))))

    w("\n"
      "  ;; p = A[p & %d] & %d -- a dependent chain through memory\n"
      "  (func (export \"k_chase\") (param $n i32) (result i32)\n"
      "    (local $i i32) (local $p i32) (local $acc i32)\n"
      "    (block $done\n"
      "      (br_if $done (i32.eqz (local.get $n)))\n"
      "%s)\n"
      "    (local.get $acc))\n"
      % (NA - 1, NA - 1,
         loop("$l",
              ["(local.set $p (i32.and (i32.load %s) (i32.const %d)))"
               % (e.at("A", e.wide_("(i32.shl (local.get $p) (i32.const 2))")), NA - 1),
               "(local.set $acc (i32.add (local.get $acc) (local.get $p)))",
               "(local.set $i (i32.add (local.get $i) (i32.const 1)))"],
              "(i32.lt_u (local.get $i) (local.get $n))")))

    w("\n"
      "  ;; What a call costs with none of the above in it, so the profiler's\n"
      "  ;; per-launch floor can be subtracted from every row.\n"
      "  (func (export \"startup\") (param i32) (result i32) (i32.const 0))\n"
      ")\n")
    return "".join(out)

def write(name, text):
    """Atomic, and a no-op when the bytes already say this -- several
    configurations regenerate these at once and each of them keys a cache on
    the file's timestamp."""
    path = os.path.join(OUT, name + ".wat")
    try:
        with open(path) as f:
            if f.read() == text:
                return
    except OSError:
        pass
    tmp = "%s.%d.tmp" % (path, os.getpid())
    with open(tmp, "w") as f:
        f.write(text)
    os.replace(tmp, path)

def main():
    os.makedirs(OUT, exist_ok=True)
    for v in ("addr32", "addrmulti", "addr64"):
        write(v, gen(v))

main()
