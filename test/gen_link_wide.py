"""A third module for the link test, generated because of its size.

Everything an instance holds lives behind one register, in arrays laid end to
end -- globals, then the { code, instance } pair per imported function, then
tables, memories and funcref cells -- and a load reaches 4095 times its access
width into that.  So how far in an *import pair* sits is decided by how many
globals the importing module happens to declare, and past 32,760 bytes the
offset has to be materialised instead of folded into the load.

That path cannot be reached by any module in test/cases: those are linked
without a host, so none of them has an import at all.  It cannot be reached by
test/link/b.wat either, which is hand-written and has four globals.  Hence
this: b.wat's shape with two thousand globals in front of it, so the pair is
past the boundary and the arguments are still in their registers when the
address is computed -- which is what makes the choice of scratch register
there load-bearing rather than arbitrary.

Usage: gen_link_wide.py OUT.wat
"""
import os
import sys

NGLOBALS = 2100

def main():
    out = sys.argv[1] if len(sys.argv) > 1 else "c.wat"
    L = ['(module',
         '  ;; Generated by test/gen_link_wide.py -- do not edit.',
         '  (import "A" "twice" (func $twice (param i32) (result i32)))',
         '  (import "A" "counter" (global $counter (mut i32)))',
         '  (import "A" "mem" (memory 1))',
         '  (import "A" "tab" (table 4 funcref))']
    for i in range(NGLOBALS):
        L.append("  (global $g%d (mut i32) (i32.const %d))" % (i, i * 3 + 1))
    L += [
        '  (type $i_i (func (param i32) (result i32)))',
        '  ;; The import pair, read from past the boundary, with the argument',
        '  ;; already in x0.',
        '  (func (export "wide_call_import") (param i32) (result i32)',
        '    (call $twice (local.get 0)))',
        '  (func (export "wide_tail_import") (param i32) (result i32)',
        '    (return_call $twice (local.get 0)))',
        '  (func (export "wide_indirect_import") (param i32) (result i32)',
        '    (call_indirect (type $i_i) (local.get 0) (i32.const 0)))',
        '  ;; An imported global, whose slot holds a pointer rather than a',
        '  ;; value, at the near end of the same array.',
        '  (func (export "wide_imported_global") (result i32)',
        '    (global.get $counter))',
        '  ;; And the far end of our own globals, which the four-byte reach of',
        '  ;; a word access runs out of at 16,380 rather than 32,760.',
        '  (func (export "wide_last_global") (result i32)',
        '    (global.set $g%d (i32.const 4242)) (global.get $g%d))'
        % (NGLOBALS - 1, NGLOBALS - 1),
        '  (func (export "wide_first_global") (result i32) (global.get $g0))',
        ')']
    tmp = "%s.%d.tmp" % (out, os.getpid())
    with open(tmp, "w") as f:
        f.write("\n".join(L) + "\n")
    os.replace(tmp, out)

main()
